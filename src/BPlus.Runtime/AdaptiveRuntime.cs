using System.Text;
using BPlus.Core.Ast;

namespace BPlus.Runtime;

public enum CpuArch { Unknown, X64_SSE2, X64_AVX, X64_AVX2, X64_AVX512, Arm64_NEON }

public record CpuCapability(string Name, CpuArch Arch, string FeatureFlag, double EstimatedIpc);

public static class CpuDetector
{
    private static readonly CpuCapability[] AllCaps =
    {
        new("SSE2", CpuArch.X64_SSE2, "sse2", 1.5),
        new("AVX", CpuArch.X64_AVX, "avx", 2.0),
        new("AVX2", CpuArch.X64_AVX2, "avx2", 2.5),
        new("AVX-512", CpuArch.X64_AVX512, "avx512f", 4.0),
        new("NEON", CpuArch.Arm64_NEON, "neon", 2.5),
    };

    public static CpuCapability DetectBest()
    {
        try
        {
            if (IsAvx512Supported()) return AllCaps[3];
            if (IsAvx2Supported()) return AllCaps[2];
            if (IsAvxSupported()) return AllCaps[1];
        }
        catch { }
        return AllCaps[0];
    }

    static bool IsAvx512Supported()
    {
        try
        {
            if (!OperatingSystem.IsWindows()) return false;
            var psi = new System.Diagnostics.ProcessStartInfo("wmic", "cpu get features") { RedirectStandardOutput = true, UseShellExecute = false, CreateNoWindow = true };
            using var p = System.Diagnostics.Process.Start(psi);
            var output = p?.StandardOutput.ReadToEnd();
            p?.WaitForExit(1000);
            return output?.Contains("AVX512F", StringComparison.OrdinalIgnoreCase) == true;
        }
        catch { return false; }
    }

    static bool IsAvx2Supported()
    {
        try
        {
